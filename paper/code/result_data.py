"""Shared accepted result data and LaTeX table construction.

Imported by the table refresher and Figure 2 script. Importing performs no writes.
The upstream masters remain unchanged; arithmetic uses unrounded JSON values.
"""
from pathlib import Path
import csv
import json
import statistics

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / 'paper'
SOURCE = ROOT / 'benchmark-results/unified-v3/tables'
TABLES = {}
e1 = json.loads((SOURCE / 'e1_cross_benchmark_generality_quality.json').read_text())
e2 = json.loads((SOURCE / 'e2_sop_model_sensitivity_master.json').read_text())
e3 = json.loads((SOURCE / 'e3_component_ablation_master.json').read_text())
assert e1['completed_cells'] == 168
assert len(e2['complete_table']) == 12 and not e2['matched_case_issues']
assert all(r['runs'] == 72 for r in e2['complete_table'])
assert len(e3['rows']) == 16 and sum(r['completed_rows'] for r in e3['rows']) == 240

def write(name, content):
    TABLES[name] = content

def table(caption, label, columns, body, note):
    return ('% Generated by paper/code/refresh-result-tables.py\n'
            '\\begin{table}[t]\n\\centering\n\\small\n'
            '\\caption{' + caption + '}\n\\label{' + label + '}\n'
            '\\setlength{\\tabcolsep}{4pt}\n'
            '\\begin{tabular}{' + columns + '}\n\\toprule\n' + body +
            '\\bottomrule\n\\end{tabular}\n\\par\\vspace{3pt}\n'
            '\\begin{minipage}{\\linewidth}\\footnotesize\n' + note +
            '\n\\end{minipage}\n\\end{table}\n')

def line(cells):
    return ' & '.join(cells) + ' \\\\\n'

# E1: retain every evaluated cell while showing each MAS label once.
lookup = {(r['mas'], r['memory_method'], r['benchmark']): r for r in e1['summary_rows']}
body = line(['MAS', 'Memory', 'ALFWorld', 'WebArena', 'OfficeBench'])
body += line(['', '', '(\\%)', '(\\%)', '(\\%)']) + '\\midrule\n'
e1_display = []
for mas, label in [('autogen', 'AutoGen'), ('dylan', 'DyLAN')]:
    if mas == 'dylan':
        body += '\\midrule\n'
    for index, (method, name) in enumerate([
        ('no-memory', 'No added memory'), ('gmemory', 'G-Memory'), ('team-memory', '\\method{}')
    ]):
        row = [label if index == 0 else '', name]
        plain = [label if index == 0 else '', 'GEMS' if method == 'team-memory' else name]
        for benchmark in ['alfworld', 'webarena', 'officebench']:
            r = lookup.get((mas, method, benchmark))
            if r is None:
                row.append('n/e'); plain.append('n/e'); continue
            value = 100*r['official_task_score_mean']
            best = max(v['official_task_score_mean'] for k, v in lookup.items() if k[0] == mas and k[2] == benchmark)
            score = f'{value:.1f}'
            if abs(r['official_task_score_mean']-best) < 1e-10:
                score = '\\textbf{' + score + '}'
            delta = 100*r['delta_vs_no_memory']
            row.append(score + (f' $({delta:+.1f})$' if method != 'no-memory' else ''))
            plain.append(f'{value:.1f}' + (f' ({delta:+.1f})' if method != 'no-memory' else ''))
        body += line(row); e1_display.append(plain)
write('tables/e1_main.tex', table(
    'Task performance across host multi-agent systems (E1). Parentheses give changes from the same host without added memory, in percentage points.',
    'tab:main', 'llrrr', body,
    'The actor and procedural-memory model are \\texttt{gpt-5-mini}. Bold denotes the best observed score within each benchmark--host block, including ties. '
    'n/e marks a combination that was not evaluated. AutoGen and DyLAN retain their native within-run context. The table reports all 168 matched runs.'))

# E2: fixed, non-performance-based order. Labels are experimental endpoint IDs.
groups = [
    ('Local', ['qwen3.5-0.8b', 'qwen3.5-2b', 'qwen3.5-9b', 'qwen3.5-27b', 'gemma-4-12b-it', 'gemma-4-31b-it']),
    ('Relay', ['deepseek-v4-flash-0731', 'qwen3.8-max', 'glm-5.2', 'kimi-k3']),
    ('Closed', ['gpt-5.6-terra', 'claude-opus-5'])]
by_model = {r['sop_model']: r for r in e2['complete_table']}
models = [m for _, ms in groups for m in ms]
benchmarks = [('alfworld', 'ALFWorld', 12, 100), ('webarena', 'WebArena', 24, 100),
              ('multiagentbench_research', 'Research', 12, 1), ('officebench', 'OfficeBench', 24, 100)]
body = line(['Memory model', 'ALFWorld', 'WebArena', 'MAB Research', 'OfficeBench'])
body += line(['', '(\\%)', '(\\%)', '(rating)', '(\\%)']) + '\\midrule\n'
e2_display, stats = [], {}
for gi, (group, ms) in enumerate(groups):
    if gi:
        body += '\\midrule\n'
    for model in ms:
        values = [f"{by_model[model][k]*scale:.{3 if scale == 1 else 1}f}" for k, _, _, scale in benchmarks]
        body += line([model] + values)
        e2_display.append([model] + values)
body += '\\midrule\n'
for k, name, n, scale in benchmarks:
    values = [by_model[m][k]*scale for m in models]
    stats[k] = dict(mean=statistics.mean(values), sd_across_models=statistics.pstdev(values),
                    minimum=min(values), maximum=max(values), span=max(values)-min(values), cases=n,
                    unit='rating points' if scale == 1 else 'percentage points')
body += line(['Across-model range'] + [f"{stats[k]['minimum']:.{3 if s == 1 else 1}f}--{stats[k]['maximum']:.{3 if s == 1 else 1}f}" for k, _, _, s in benchmarks])
write('tables/e2_models.tex', table(
    'Task scores under 12 configured procedural-memory model identifiers (E2). AutoGen and the actor \\texttt{gpt-5-mini} are fixed; each model block contains the same 72 cases.',
    'tab:procedure_model', 'lrrrr', body,
    'Case counts are 12/24/12/24 for ALFWorld/WebArena/MultiAgentBench Research/OfficeBench. '
    'The three percentage columns are official means multiplied by 100; Research retains its native rating scale. '
    'Horizontal rules separate local, relay, and closed model groups from the run configuration. '
    'Model names are recorded endpoint identifiers. Ranges describe the 12 observed model means, not confidence intervals.'))

# E3: condition names carry the component configuration; metric columns stay compact.
conditions = [('no-extra-components', 'No added components'),
              ('sop-only', 'Memory only'),
              ('divergence-only', 'Alignment only'),
              ('full', 'Full \\method{}')]
e3_bench = [('ALFWorld', 100), ('WebArena', 100), ('MultiAgentBench Research', 1), ('OfficeBench', 100)]
r3 = {(r['condition'], r['benchmark']): r for r in e3['rows']}
body = line(['Condition', 'ALFWorld', 'WebArena', 'MAB Research', 'OfficeBench'])
body += line(['', '(\\%)', '(\\%)', '(rating)', '(\\%)']) + '\\midrule\n'
e3_display = []
for condition, name in conditions:
    row, plain = [name], [name.replace('\\method{}', 'GEMS')]
    for benchmark, scale in e3_bench:
        value = r3[condition, benchmark]['official_task_score_mean']*scale
        best = max(r3[c, benchmark]['official_task_score_mean'] for c, _ in conditions)*scale
        s = f'{value:.{3 if scale == 1 else 1}f}'
        plain.append(s)
        row.append('\\textbf{'+s+'}' if abs(value-best)<1e-10 else s)
    body += line(row); e3_display.append(plain)
body += '\\midrule\n'
contrasts = {}
for key, desc, positive, negative in [('joint', 'Full $-$ no added', 'full', 'no-extra-components'),
                                     ('c1', 'Full $-$ alignment only', 'full', 'divergence-only'),
                                     ('c3', 'Full $-$ memory only', 'full', 'sop-only')]:
    values = [(r3[positive, b]['official_task_score_mean']-r3[negative, b]['official_task_score_mean'])*s for b,s in e3_bench]
    contrasts[key] = dict(zip([b for b,_ in e3_bench], values))
    cells = [f'{v:+.{3 if s == 1 else 1}f}' for v, (_,s) in zip(values, e3_bench)]
    body += desc+' & '+' & '.join(cells)+' \\\\\n'
write('tables/e3_contributions.tex', table(
    'Matched component-switch configurations (E3). All conditions use AutoGen, \\texttt{gpt-5-mini}, and matched cases. The lower block reports contrasts between the same four conditions.',
    'tab:ablation', 'lrrrr', body,
    'Memory only enables procedural memory and the shared blackboard; alignment only enables divergence detection and the shared blackboard; Full enables all three components. '
    'ALFWorld, WebArena, and OfficeBench use percentages and percentage-point contrasts; MAB Research uses its native rating and rating-point contrasts. '
    'These are configuration contrasts: retrieval counts are zero, and verified realignment is not established. The blackboard has no independent removal condition. Bold marks observed column maxima, including ties.'))

